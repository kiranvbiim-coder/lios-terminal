import { useEffect, useState, type ReactNode } from "react";
import type { ViewMode } from "@/lib/terminalTypes";
import { loadTerminalViewState, patchTerminalViewState } from "@/lib/terminalViewState";
import EconCalendarPanel from "./EconCalendarPanel";
import EconomicSignalsPanel from "./EconomicSignalsPanel";
import EconomicsOverviewPanel from "./EconomicsOverviewPanel";
import EconomicsPolicyQuantPanel from "./EconomicsPolicyQuantPanel";
import IndicatorWorkbenchPanel from "./IndicatorWorkbenchPanel";
import MacroDashboardPanel from "./MacroDashboardPanel";
import { InstitutionalWorkspaceShell, MethodologyCard, WorkstationOverview } from "./workstations/InstitutionalWorkspaceShell";
import { WORKSTATION_DEFINITIONS } from "./workstations/workstationDefinitions";

type Section = "overview" | "macro" | "signals" | "policy" | "indicators" | "calendar";
const SECTIONS = new Set<Section>(["overview", "macro", "signals", "policy", "indicators", "calendar"]);

interface Props {
  onNav?: (view: ViewMode) => void;
  onSymbol?: (symbol: string) => void;
}

function initialSection(): Section {
  const value = loadTerminalViewState("economics").section;
  return typeof value === "string" && SECTIONS.has(value as Section) ? value as Section : "macro";
}

export default function EconomicsPanel({ onNav, onSymbol }: Props = {}) {
  // Operational economics opens on observable macro conditions. The internal
  // section is persisted so a saved analytical workspace returns to the same
  // macro/signals/policy/calendar mode instead of resetting to a landing page.
  const [section, setSection] = useState<Section>(initialSection);
  const definition = WORKSTATION_DEFINITIONS.economics;
  const navigate = onNav ?? (() => undefined);
  const selectSymbol = onSymbol ?? (() => undefined);

  useEffect(() => {
    patchTerminalViewState("economics", undefined, { section });
  }, [section]);

  let body: ReactNode;
  if (section === "macro") {
    body = (
      <div className="h-full min-h-0 overflow-y-auto scrollbar-thin">
        <div className="min-h-full grid grid-cols-1 xl:grid-cols-[1.35fr_0.65fr]">
          <div className="min-h-[420px] border-b xl:border-b-0 xl:border-r border-border"><MacroDashboardPanel onNav={navigate} /></div>
          <div className="min-h-[420px]"><EconomicsOverviewPanel onOpenCalendar={() => setSection("calendar")} /></div>
        </div>
      </div>
    );
  } else if (section === "signals") body = <EconomicSignalsPanel />;
  else if (section === "policy") body = <EconomicsPolicyQuantPanel />;
  else if (section === "indicators") body = <IndicatorWorkbenchPanel />;
  else if (section === "calendar") body = <EconCalendarPanel onNav={navigate} onSymbol={selectSymbol} />;
  else {
    body = (
      <div className="h-full overflow-y-auto scrollbar-thin">
        <WorkstationOverview
          definition={definition}
          onSection={(next) => setSection(next as Section)}
          headline="Macro data becomes useful when it leads to an explicit policy or company implication."
          description="The economics surface separates the job into observable macro conditions, derived signals, deterministic policy models, a transformation/econometrics lab, and a source-backed event calendar."
          trustItems={[
            "Live economic series stay distinct from analyst-entered assumptions and synthetic micro-populations.",
            "Taylor/Phillips and other deterministic outputs are calculated by the existing engines, not generated by AI.",
            "Tax/carbon distributional models explicitly distinguish uploaded client microdata from generated illustrative populations.",
            "The calendar renders source-backed events only; implied-rate probabilities remain unavailable until a real source is connected.",
          ]}
        />
        <div className="mx-auto max-w-6xl px-4 pb-5">
          <div className="grid grid-cols-1 gap-2 lg:grid-cols-2">
            <MethodologyCard title="TAYLOR RULE" formula="i* = r* + π + a(π − π*) + b(y − y*)" detail="A policy-rule benchmark, not a forecast of the central bank's actual decision. Inflation, target, neutral rate, and output gap assumptions must remain visible." />
            <MethodologyCard title="PHILLIPS RELATIONSHIP" formula="πₜ = α + βuₜ + εₜ" detail="The fitted relationship is historical/statistical. Structural breaks, expectations, supply shocks, and regime changes can invalidate a stable-coefficient interpretation." />
            <MethodologyCard title="LEONTIEF INPUT-OUTPUT" formula="x = (I − A)⁻¹d" detail="Maps final-demand shocks through an input-output coefficient matrix. Results are only as current and representative as the supplied sector matrix." />
            <MethodologyCard title="DISTRIBUTIONAL MODELS" detail="Gini, tax microsimulation, and carbon-tax/dividend analysis need household-level distributions. LIOS labels generated populations as illustrative and supports uploaded data for client-specific analysis." />
          </div>
        </div>
      </div>
    );
  }

  return (
    <InstitutionalWorkspaceShell definition={definition} activeSection={section} onSection={(next) => setSection(next as Section)} status={{ label: "REPRODUCIBLE VIEW STATE", tone: "ok" }}>
      {body}
    </InstitutionalWorkspaceShell>
  );
}
