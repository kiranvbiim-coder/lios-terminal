import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
const root = fs.mkdtempSync(path.join(os.tmpdir(), "lios-thesis-monitor-review-"));
process.env.LIOS_DATA_ROOT = root;
process.env.LIMURIA_DATA_DIR = root;
delete process.env.DATABASE_URL;
const { initDb, closeDb, getDb } = await import("./db");
const { users } = await import("@shared/schema");
const { thesisArtifactContentSchema } = await import("@shared/artifactContracts");
const { createProject } = await import("./projectStore");
const { createArtifact, getArtifact, getArtifactVersion, listArtifactProposals, decideArtifactProposal } = await import("./artifactStore");
const { indexProjectDocument } = await import("./p7ProjectIntelligenceStore");
const { createP9Workflow } = await import("./p9AutomationStore");
const { executeP9Workflow } = await import("./p9AutomationService");

test("typed thesis invalidation produces one review proposal without silently changing the owner's thesis", { timeout: 120_000 }, async (t) => {
  await initDb();
  t.after(async () => { await closeDb(); fs.rmSync(root, { recursive: true, force: true }); });
  const [owner] = await getDb().insert(users).values({ name: "Thesis owner", email: `${crypto.randomUUID()}@example.test`, passwordHash: "test-only", role: "internal_admin", organizationId: null }).returning();
  const ctx = { userId: owner.id, organizationId: null, role: owner.role };
  const project = await createProject(ctx, { name: "Explicit thesis review" });
  const original = thesisArtifactContentSchema.parse({ kind: "thesis", status: "active", summary: "Owner thesis", claims: [{ id: "claim-margin", text: "Margins expand" }], invalidationConditions: [{ id: "margin-contract", text: "Margins contract" }] });
  const artifact = await createArtifact(ctx, { projectId: project.id, title: "Owner margin thesis", content: original });
  await indexProjectDocument(ctx, { projectId: project.id, sourceType: "research_evidence", sourceRef: "fixture:explicit-margin-condition", title: "Explicit isolated invalidation evidence", body: "This is a typed fixture, not company/provider evidence.", metadata: { thesisSignals: [{ type: "invalidation_triggered", targetId: "margin-contract" }] } });
  const workflow = await createP9Workflow(ctx, project.id, { name: "Review thesis invalidation", template: "thesis_refresh", enabled: false, trigger: { type: "manual" }, action: { kind: "thesis_refresh", artifactId: artifact.artifact.id }, notificationPolicy: { enabled: true, notifyOn: ["condition_met", "change_detected"], cooldownMinutes: 0, suppressUnchanged: true } });
  const first = await executeP9Workflow({ ctx, workflow, triggerType: "manual" });
  assert.equal(first.run?.status, "succeeded", first.error ?? undefined);
  assert.equal((await getArtifact(ctx, artifact.artifact.id)).headVersion, 1, "background evidence cannot overwrite owner state");
  assert.equal((await getArtifactVersion(ctx, artifact.artifact.id)).content.status, "active");
  const proposals = await listArtifactProposals(ctx, artifact.artifact.id);
  assert.equal(proposals.length, 1);
  assert.equal(proposals[0]!.status, "pending");
  assert.equal(first.result?.output.proposalId, proposals[0]!.id);
  const repeat = await executeP9Workflow({ ctx, workflow, triggerType: "manual" });
  assert.equal(repeat.run?.status, "succeeded", repeat.error ?? undefined);
  assert.equal((await listArtifactProposals(ctx, artifact.artifact.id)).length, 1);
  assert.equal(repeat.result?.changed, false);
  assert.equal(repeat.notification?.status, "suppressed");
  await decideArtifactProposal(ctx, proposals[0]!.id, "accept");
  assert.equal((await getArtifactVersion(ctx, artifact.artifact.id)).content.status, "invalidated", "only explicit owner acceptance changes the canonical thesis");
});
