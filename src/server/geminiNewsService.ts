import { fetchText } from "./providerUtils";
import { XMLParser } from "fast-xml-parser";
import { invokeAIRoutedCompletion } from "./byoaiTransport";
import { recordConnectorVerification } from "./connectorVerification";


const parser = new XMLParser({ ignoreAttributes: false, attributeNamePrefix: "@_" });

export interface GeminiAnalyzedNews {
  query: string;
  articles: Array<{
    title: string;
    link: string;
    published: string;
    source?: string;
  }>;
  analysis: string;
  modelUsed: string;
}

/**
 * Searches Google News RSS for a ticker/query and runs the shared BYOAI
 * provider registry to produce a financial news synthesis and sentiment
 * breakdown.
 */
export async function getGeminiNewsAnalysis(query: string): Promise<GeminiAnalyzedNews> {

  // 1. Fetch Google News RSS Feed for query
  const rssUrl = `https://news.google.com/rss/search?q=${encodeURIComponent(query)}&hl=en-IN&gl=IN&ceid=IN:en`;
  let xmlText: string;
  try {
    xmlText = await fetchText(rssUrl);
    recordConnectorVerification("news:google_rss", true, "Google News RSS returned a live attributed feed.");
  } catch (error) {
    recordConnectorVerification("news:google_rss", false, error instanceof Error ? error.message : "Google News RSS fetch failed.");
    throw error;
  }

  const parsed = parser.parse(xmlText);
  const rawItems = parsed?.rss?.channel?.item ?? [];
  const items = Array.isArray(rawItems) ? rawItems : [rawItems];

  const articles = items.slice(0, 5).map((item: any) => ({
    title: String(item?.title ?? "No title"),
    link: String(item?.link ?? "No link"),
    published: String(item?.pubDate ?? "Unknown date"),
    source: typeof item?.source === "string" ? item.source : item?.source?.["#text"] || "Google News",
  }));

  if (!articles.length) {
    return {
      query,
      articles: [],
      analysis: "No recent news articles found for this topic.",
      modelUsed: "None",
    };
  }

  // 2. Format articles for Gemini prompt
  const newsText = articles
    .map(
      (art, i) => `ARTICLE ${i + 1}\nTitle: ${art.title}\nPublished: ${art.published}\nSource: ${art.source}\nLink: ${art.link}`
    )
    .join("\n\n");
  const prompt = `You are a senior financial analyst assistant. Below are recent news articles discovered through Google News RSS for: "${query}". Analyze them and provide:
1. Overall stock/business summary and key market sentiment impact.
2. 3 key bullish or bearish takeaways.
3. A concise one-sentence executive summary for each article.

Do NOT invent information that isn't present in the article metadata.

NEWS ARTICLES:
${newsText}`;

  const result = await invokeAIRoutedCompletion({
    messages: [{ role: "user", content: prompt }],
  });

  return {
    query,
    articles,
    analysis: result.text || "No synthesis generated by AI.",
    modelUsed: result.model,
  };
}
