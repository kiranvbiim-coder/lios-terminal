import { eq } from "drizzle-orm";
import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
const root = fs.mkdtempSync(path.join(os.tmpdir(), "lios-finance-monitor-retention-"));
process.env.LIOS_DATA_ROOT = root;
process.env.LIMURIA_DATA_DIR = root;
process.env.LIOS_CODEX_CLI_PATH = "/nonexistent/lios-offline-codex";
process.env.LIOS_CLAUDE_CLI_PATH = "/nonexistent/lios-offline-claude";
delete process.env.DATABASE_URL;
const { initDb, closeDb, getDb } = await import("./db");
const { users } = await import("@shared/schema");
const { createProject } = await import("./projectStore");
const { createProjectChat } = await import("./projectChatStore");
const { createP9Workflow } = await import("./p9AutomationStore");
const { executeP9Workflow } = await import("./p9AutomationService");
const { getArtifact, getArtifactVersion, createArtifactVersion } = await import("./artifactStore");
const { p9WorkflowActionSchema } = await import("@shared/p9AutomationContracts");
const { createProjectResource, updateProjectResourceMetadata, archiveProjectResource, getProjectResource } = await import("./projectResourceStore");

test("a deterministic finance rerun retains canonical output and compares content rather than fresh receipt identities", { timeout: 120_000 }, async (t) => {
  await initDb();
  t.after(async () => { await closeDb(); fs.rmSync(root, { recursive: true, force: true }); });
  const [owner] = await getDb().insert(users).values({ name: "Finance monitor owner", email: `${crypto.randomUUID()}@example.test`, passwordHash: "test-only", role: "internal_admin", organizationId: null }).returning();
  const ctx = { userId: owner.id, organizationId: null, role: owner.role };
  const project = await createProject(ctx, { name: "Retained financial monitor" });
  const chat = await createProjectChat(ctx, { projectId: project.id, scope: "project", title: "Financial workflow" });
  const workflow = await createP9Workflow(ctx, project.id, {
    name: "Personal financial review", template: "custom", enabled: false, trigger: { type: "manual" },
    action: { kind: "conversation_rerun", chatId: chat.id, request: { message: "Calculate my personal finances", executionMode: "deterministic_first", sourceScope: "my_data", context: { personalFinance: { schemaVersion: "1", asOf: "2026-09-22", accounts: [{ id: "bank", kind: "bank", balance: 200000, currency: "INR" }], transactions: [], debts: [], goals: [], retirement: null } } } },
    notificationPolicy: { enabled: true, notifyOn: ["change_detected"], suppressUnchanged: true, cooldownMinutes: 0 },
  });
  const first = await executeP9Workflow({ ctx, workflow, triggerType: "manual" });
  assert.equal(first.error, null);
  assert.equal(first.run?.status, "succeeded");
  const ref = first.result!.artifactRefs.find(id => id.startsWith("artifact:"));
  assert.ok(ref, "background financial outputs must be canonical retained Artifacts, not ephemeral draft UUIDs");
  const artifact = await getArtifact(ctx, ref);
  const version = await getArtifactVersion(ctx, artifact.id);
  assert.equal(artifact.projectId, project.id);
  assert.equal(version.content.kind, "decision");
  assert.ok(version.executionReceiptIds.every(id => first.result!.executionReceiptIds.includes(id)));
  const second = await executeP9Workflow({ ctx, workflow, triggerType: "manual" });
  assert.equal(second.error, null);
  assert.equal(second.result?.changed, false, "new request/receipt/draft UUIDs must not turn unchanged financial results into a material change");
  assert.equal(second.notification?.status, "suppressed");
  assert.equal(second.result?.output.outputHash, first.result?.output.outputHash);
  await t.test("finance monitor acceptance binds real retained work and rejects changed recipes or baseline heads", async () => {
    const action = p9WorkflowActionSchema.parse(workflow.action);
    if (action.kind !== "conversation_rerun") throw new Error("Expected saved finance request");
    const acceptedArtifact = { artifactId: artifact.id, version: version.version, contentHash: version.contentHash };
    const monitorInput = { name: "Accepted financial review monitor", template: "report_refresh", enabled: false, trigger: { type: "manual" }, notificationPolicy: { enabled: false }, action: { ...action, acceptedArtifact } };
    await assert.rejects(createP9Workflow(ctx, project.id, { ...monitorInput, action }), /accepted|Artifact|Invalid/i);
    await assert.rejects(createP9Workflow(ctx, project.id, { ...monitorInput, action: { ...action, acceptedArtifact: { ...acceptedArtifact, contentHash: "0".repeat(64) } } }), /hash/i);
    await assert.rejects(createP9Workflow(ctx, project.id, { ...monitorInput, action: { ...action, acceptedArtifact, request: { ...action.request, message: "Different financial calculation" } } }), /recipe/i);
    await assert.rejects(createP9Workflow(ctx, project.id, { ...monitorInput, action: { ...action, acceptedArtifact, request: { ...action.request, context: {} } } }), /inputs|custody|policy/i);
    const otherChat = await createProjectChat(ctx, { projectId: project.id, scope: "project", title: "Unrelated recipe" });
    await assert.rejects(createP9Workflow(ctx, project.id, { ...monitorInput, action: { ...action, chatId: otherChat.id, acceptedArtifact } }), /another Project or Chat/i);
    const otherProject = await createProject(ctx, { name: "Unrelated monitor scope" });
    await assert.rejects(createP9Workflow(ctx, otherProject.id, monitorInput), /Project/i);
    const monitor = await createP9Workflow(ctx, project.id, monitorInput);
    const run = await executeP9Workflow({ ctx, workflow: monitor, triggerType: "manual" });
    assert.equal(run.run?.status, "succeeded", run.error ?? undefined);
    assert.ok(run.result!.artifactRefs.some(id => id.startsWith("artifact:")));
    const profile = action.request.context?.personalFinance;
    assert.ok(profile);
    const resource = await createProjectResource(ctx, { projectId: project.id, kind: "personal_finance_profile", label: "Owner financial inputs", resourceRef: "lios:personal-finance-profile", contextMode: "excluded", metadata: { profile } });
    const following = await createP9Workflow(ctx, project.id, { ...monitorInput, name: "Explicit current-source monitor", action: { ...action, acceptedArtifact, currentPersonalFinanceResourceId: resource.id } });
    const baseline = await executeP9Workflow({ ctx, workflow: following, triggerType: "manual" });
    assert.equal(baseline.run?.status, "succeeded");
    const updatedProfile = { ...profile, accounts: profile.accounts.map(account => ({ ...account, balance: 250000 })) };
    await updateProjectResourceMetadata(ctx, resource.id, { profile: updatedProfile });
    const refreshed = await executeP9Workflow({ ctx, workflow: following, triggerType: "manual" });
    assert.equal(refreshed.run?.status, "succeeded", refreshed.error ?? undefined);
    assert.equal(refreshed.result?.changed, true);
    assert.match(String(refreshed.result?.output.text), /250000/);
    assert.notEqual((refreshed.result?.output.currentInput as { inputHash: string }).inputHash, (baseline.result?.output.currentInput as { inputHash: string }).inputHash);
    assert.equal((await getProjectResource(ctx, resource.id)).contextMode, "excluded", "source refresh never enables ordinary AI sharing");
    await archiveProjectResource(ctx, resource.id);
    const missing = await executeP9Workflow({ ctx, workflow: following, triggerType: "manual" });
    assert.equal(missing.run?.status, "failed");
    assert.match(missing.error ?? "", /source.*unavailable/i);
    assert.deepEqual(missing.run?.artifactRefs, [], "removed source must not silently replay frozen inputs");
    await createArtifactVersion(ctx, { artifactId: artifact.id, baseVersion: version.version, content: version.content, actorType: "user", note: "Owner accepted a new baseline revision" });
    const stale = await executeP9Workflow({ ctx, workflow: monitor, triggerType: "manual" });
    assert.equal(stale.run?.status, "failed");
    assert.match(stale.error ?? "", /head changed/i);
    assert.deepEqual(stale.run?.artifactRefs, [], "stale acceptance cannot produce new financial outputs");
  });
  await getDb().update(users).set({ active: false }).where(eq(users.id, owner.id));
  await assert.rejects(executeP9Workflow({ ctx, workflow, triggerType: "manual" }), /current|inactive|disabled|authority/i);
  await getDb().update(users).set({ active: true, mustChangePassword: true }).where(eq(users.id, owner.id));
  await assert.rejects(executeP9Workflow({ ctx, workflow, triggerType: "manual" }), /current|password|authority/i);
  await getDb().update(users).set({ mustChangePassword: false, lockedUntil: new Date(Date.now() + 60_000) }).where(eq(users.id, owner.id));
  await assert.rejects(executeP9Workflow({ ctx, workflow, triggerType: "manual" }), /current|locked|authority/i);
});
