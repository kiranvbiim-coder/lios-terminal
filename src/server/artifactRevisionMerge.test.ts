import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'lios-branch-merge-'));
process.env.LIMURIA_DATA_DIR=dir;
const {initDb,getDb,closeDb}=await import('./db');
const {users}=await import('@shared/schema');
const {createProject}=await import('./projectStore');
const store=await import('./artifactStore');
const {proposeArtifactBranchMerge}=await import('./artifactRevisionMerge');
const {artifactContentSchema}=await import('@shared/artifactContracts');

test('P4 branch reconciliation binds ancestry, exposes conflicts and requires reviewed acceptance',{timeout:30000},async(t)=>{
  await initDb();
  t.after(async()=>{await closeDb();fs.rmSync(dir,{recursive:true,force:true});});
  const [user]=await getDb().insert(users).values({email:crypto.randomUUID()+'@test.invalid',passwordHash:'test',role:'internal_analyst',name:'Merge owner',organizationId:null}).returning();
  const ctx={userId:user.id,role:user.role,organizationId:null};
  const project=await createProject(ctx,{name:'Branch test'});
  const content=artifactContentSchema.parse({kind:'report',blocks:[{id:'authored',type:'paragraph',text:'Base authored text',attrs:{sourceRef:'source:authored'}}],sections:[],templateId:'base'});
  const target=await store.createArtifact(ctx,{projectId:project.id,title:'Report',content,sourceRefs:['source:authored']});
  const branch=await store.forkArtifact(ctx,{artifactId:target.artifact.id,title:'Review branch'});
  await store.createArtifactVersion(ctx,{artifactId:target.artifact.id,baseVersion:1,content:artifactContentSchema.parse({...content,templateId:'target'})});
  await store.createArtifactVersion(ctx,{artifactId:branch.artifact.id,baseVersion:1,content:artifactContentSchema.parse({...content,templateId:'branch',blocks:[{id:'authored',type:'paragraph',text:'Branch authored text',attrs:{sourceRef:'source:authored'}}]})});
  const review=await proposeArtifactBranchMerge(ctx,target.artifact.id,{branchArtifactId:branch.artifact.id,branchVersion:2,targetVersion:2});
  assert.deepEqual(review.conflictPreviews.templateId,{target:'"target"',branch:'"branch"',truncated:false});
  assert.deepEqual(review.conflicts,['templateId']);
  assert.equal(review.proposal,null);
  assert.equal((await store.listArtifactProposals(ctx,target.artifact.id)).length,0);
  const resolved=await proposeArtifactBranchMerge(ctx,target.artifact.id,{branchArtifactId:branch.artifact.id,branchVersion:2,targetVersion:2,resolutions:{templateId:'target'}});
  assert.ok(resolved.proposal);
  assert.equal((await store.getArtifact(ctx,target.artifact.id)).headVersion,2,'proposal is not an automatic merge');
  const accepted=await store.decideArtifactProposal(ctx,resolved.proposal.id,'accept');
  assert.ok(accepted.version);
  const merged=artifactContentSchema.parse(accepted.version.content);
  assert.equal(merged.kind,'report');
  if(merged.kind!=='report')throw Error('Wrong kind');
  assert.equal(merged.templateId,'target');
  assert.equal(merged.blocks[0].text,'Branch authored text');
  assert.deepEqual(await store.getArtifactVersion(ctx,target.artifact.id,1),target.version);
  await assert.rejects(proposeArtifactBranchMerge(ctx,target.artifact.id,{branchArtifactId:branch.artifact.id,branchVersion:2,targetVersion:2}),/head moved/);
  const unrelated=await store.createArtifact(ctx,{projectId:project.id,title:'Unrelated',content});
  await assert.rejects(proposeArtifactBranchMerge(ctx,target.artifact.id,{branchArtifactId:unrelated.artifact.id,branchVersion:1,targetVersion:3}),/direct fork/);
  await assert.rejects(proposeArtifactBranchMerge(ctx,target.artifact.id,{branchArtifactId:branch.artifact.id,branchVersion:2,targetVersion:3,resolutions:{blocks:'branch'}}),/does not name a current conflict/);
});
