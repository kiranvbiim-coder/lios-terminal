import assert from "node:assert/strict";
import test from "node:test";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
const root = fs.mkdtempSync(path.join(os.tmpdir(), "lios-office-return-"));
process.env.LIMURIA_DATA_DIR = root;
const { initDb, closeDb, getDb } = await import("./db");
const { users } = await import("@shared/schema");
const { createProject } = await import("./projectStore");
const store = await import("./artifactStore");
const { proposeOfficeArtifactReturn } = await import("./officeArtifactReturn");
const { artifactContentSchema } = await import("@shared/artifactContracts");

test("Office edits require owned immutable source custody and explicit P4 acceptance", { timeout: 30_000 }, async t => {
  await initDb();
  t.after(async () => { await closeDb(); fs.rmSync(root, { recursive: true, force: true }); });
  const [owner, foreign] = await getDb().insert(users).values(["owner", "foreign"].map(name => ({ email: `${crypto.randomUUID()}@test.invalid`, passwordHash: "test-only", name, role: "internal_analyst" as const, organizationId: null }))).returning();
  const ctx = { userId: owner.id, organizationId: null, role: owner.role };
  const project = await createProject(ctx, { name: "Office return" });
  const content = artifactContentSchema.parse({ kind: "report", blocks: [{ id: "authored", type: "paragraph", text: "Authored source", attrs: { sourceRef: "source:authored" } }], sections: [], templateId: null });
  const original = await store.createArtifact(ctx, { projectId: project.id, title: "Authored work", content, sourceRefs: ["source:authored"] });
  const input = { sourceArtifactId: original.artifact.id, sourceVersion: 1, sourceHash: original.version.contentHash, sourceContent: content, content: artifactContentSchema.parse({ ...content, blocks: [{ id: "authored", type: "paragraph", text: "Actual edited Office text", attrs: { sourceRef: "source:authored", officeEdited: true } }] }), format: "docx" as const, fileHash: "a".repeat(64), warnings: [] };
  const staged = await proposeOfficeArtifactReturn(ctx, original.artifact.id, input);
  assert.ok(staged.proposal);
  assert.equal((await store.getArtifact(ctx, original.artifact.id)).headVersion, 1);
  assert.deepEqual(await store.getArtifactVersion(ctx, original.artifact.id, 1), original.version);
  assert.equal((await proposeOfficeArtifactReturn(ctx, original.artifact.id, input)).proposal?.id, staged.proposal.id);
  await assert.rejects(proposeOfficeArtifactReturn({ ...ctx, userId: foreign.id }, original.artifact.id, input), /not found|owned/);
  await assert.rejects(proposeOfficeArtifactReturn(ctx, original.artifact.id, { ...input, sourceContent: input.content }), /custody/);
  await assert.rejects(proposeOfficeArtifactReturn(ctx, original.artifact.id, { ...input, sourceHash: "b".repeat(64) }), /custody/);
  const unchanged = await proposeOfficeArtifactReturn(ctx, original.artifact.id, { ...input, content });
  assert.equal(unchanged.changed, false); assert.equal(unchanged.proposal, null);
  const accepted = await store.decideArtifactProposal(ctx, staged.proposal.id, "accept");
  assert.ok(accepted.version); assert.equal(accepted.version.version, 2);
  assert.deepEqual(accepted.version.sourceRefs, ["source:authored"]);
  const returned = artifactContentSchema.parse(accepted.version.content);
  if (returned.kind !== "report") throw new Error("Expected report.");
  assert.equal(returned.blocks[0].text, "Actual edited Office text");
  assert.equal(returned.blocks[0].attrs.sourceRef, "source:authored");
  assert.equal(returned.blocks[0].attrs.officeEdited, true);
  assert.equal(returned.blocks[0].attrs.sourceQuoteEdited, true);
  assert.equal(returned.blocks[0].attrs.officeEditProvenance, "user_asserted");
  const cited = artifactContentSchema.parse({ kind: "research", question: "Authored question", blocks: [{ id: "quote", type: "quote", text: "Authored cited quotation", attrs: { sourceRef: "source:authored" } }], claims: [{ id: "claim", text: "Authored cited claim", provenance: "source_backed", sourceRefs: ["source:authored"] }] });
  const research = await store.createArtifact(ctx, { projectId: project.id, title: "Cited source", content: cited, sourceRefs: ["source:authored"] });
  if (cited.kind !== "research") throw new Error("Expected research.");
  const forged = artifactContentSchema.parse({ ...cited, blocks: [{ ...cited.blocks[0], text: "Edited unsupported quote" }], claims: [{ ...cited.claims[0], text: "Edited unsupported claim" }] });
  const provenanceReview = await proposeOfficeArtifactReturn(ctx, research.artifact.id, { ...input, sourceArtifactId: research.artifact.id, sourceHash: research.version.contentHash, sourceContent: cited, content: forged });
  assert.ok(provenanceReview.proposal);
  const provenanceAccepted = await store.decideArtifactProposal(ctx, provenanceReview.proposal.id, "accept");
  const corrected = artifactContentSchema.parse(provenanceAccepted.version!.content);
  if (corrected.kind !== "research") throw new Error("Expected research.");
  assert.equal(corrected.claims[0].provenance, "user_asserted", "Home must not trust file-derived source_backed edit claims");
  assert.equal(corrected.blocks[0].attrs.sourceQuoteEdited, true);
  assert.equal(corrected.blocks[0].attrs.officeEditProvenance, "user_asserted");
  await assert.rejects(proposeOfficeArtifactReturn(ctx, original.artifact.id, input), /head moved/);
});
