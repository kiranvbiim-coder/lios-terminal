import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import test from "node:test";
const root = fs.mkdtempSync(path.join(os.tmpdir(), "lios-project-monitor-"));
process.env.LIOS_DATA_ROOT = root;
process.env.LIMURIA_DATA_DIR = root;
delete process.env.DATABASE_URL;
const { initDb, closeDb, getDb } = await import("./db");
const { users } = await import("@shared/schema");
const { createProject } = await import("./projectStore");
const { createProjectResource } = await import("./projectResourceStore");
const { createP9Workflow } = await import("./p9AutomationStore");
const { executeP9Workflow } = await import("./p9AutomationService");

test("Project monitoring reports source changes but not its own execution bookkeeping", { timeout: 120_000 }, async t => {
  await initDb();
  t.after(async () => { await closeDb(); fs.rmSync(root, { recursive: true, force: true }); });
  const [owner] = await getDb().insert(users).values({ name: "Monitor owner", email: `${crypto.randomUUID()}@example.test`, passwordHash: "verification-only", role: "internal_admin", organizationId: null }).returning();
  assert.ok(owner);
  const ctx = { userId: owner.id, organizationId: null, role: owner.role };
  const project = await createProject(ctx, { name: "Source monitor" });
  const workflow = await createP9Workflow(ctx, project.id, { name: "Source changes", enabled: false, trigger: { type: "manual" }, action: { kind: "project_what_changed" }, notificationPolicy: { cooldownMinutes: 0 } });
  const run = () => executeP9Workflow({ workflow, ctx, triggerType: "manual" });
  assert.equal((await run()).result?.changed, false, "first observation establishes a baseline");
  assert.equal((await run()).result?.changed, false, "own receipt/planning records are not a source change");
  const resource = await createProjectResource(ctx, { projectId: project.id, kind: "document", label: "Owned research input", metadata: { text: "Explicit research source" } });
  const changed = await run();
  assert.equal(changed.result?.changed, true);
  assert.ok(changed.result?.sourceRefs.some(ref => ref.includes(resource.id)));
  assert.equal(changed.notification?.status, "delivered", "actual source addition should deliver a material-change notice");
  const unchanged = await run();
  assert.equal(unchanged.result?.changed, false);
  assert.equal(unchanged.notification?.status, "suppressed", "source unchanged must stay quiet despite previous monitoring receipts");
});
